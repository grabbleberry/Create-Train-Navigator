// Inside your Train Mixin class that intercepts Create's train movement mechanics
@Inject(method = "maxSpeed", at = @At("RETURN"), cancellable = true)
private void applyDieselElectricSpeedBoost(CallbackInfoReturnable<Float> cir) {
    Train self = (Train) (Object) this;
    
    // Check our NBT storage data generated by the engine's MovementBehaviour
    boolean active = self.carriages.get(0).storageData.getBoolean("PowertrainActive");
    
    if (active) {
        int cylinders = self.carriages.get(0).storageData.getInt("CylinderCount");
        
        // Grab Create's base config train speed (usually around 0.4 or 0.5)
        float defaultMaxSpeed = cir.getReturnValue();
        
        // Add 0.2 blocks/tick per cylinder to the top speed value!
        float modifiedTopSpeed = defaultMaxSpeed + (cylinders * 0.2f);
        
        cir.setReturnValue(modifiedTopSpeed);
    }
}

